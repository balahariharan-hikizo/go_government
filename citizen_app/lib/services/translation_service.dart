  /// Synchronous translation lookup (instant, 0ms, no network delay).
  /// Checks built-in dictionary first, then dynamic in-memory cache.
  static String translateSync(String text) {
    if (text.trim().isEmpty) return text;
    final code = languageNotifier.value;
    if (code == 'en') return text;

    final trimmed = text.trim();
    final dict = _dictionary[code];

    if (dict != null) {
      // 1. Direct exact match
      if (dict.containsKey(trimmed)) {
        return dict[trimmed]!;
      }

      // 2. Case-insensitive match
      final lowerKey = trimmed.toLowerCase();
      for (final entry in dict.entries) {
        if (entry.key.toLowerCase() == lowerKey) {
          return entry.value;
        }
      }

      // 3. Normalized whitespace match (replaces newlines with spaces)
      final normalized = trimmed.replaceAll('\n', ' ').replaceAll(RegExp(r'\s+'), ' ');
      for (final entry in dict.entries) {
        final entryNorm = entry.key.replaceAll('\n', ' ').replaceAll(RegExp(r'\s+'), ' ');
        if (entryNorm.toLowerCase() == normalized.toLowerCase()) {
          return entry.value;
        }
      }

      // 4. Strip trailing ellipsis / dots if present
      if (trimmed.endsWith('...')) {
        final stripped = trimmed.substring(0, trimmed.length - 3).trim();
        if (dict.containsKey(stripped)) {
          return '${dict[stripped]}...';
        }
      }

      // 5. Composite greeting like "Good Morning, Alex.." or "Good Morning! Welcome"
      for (final greeting in ['Good Morning', 'Good Afternoon', 'Good Evening']) {
        if (text.startsWith(greeting)) {
          final translatedGreeting = dict[greeting] ?? greeting;
          final rest = text.substring(greeting.length);
          return '$translatedGreeting$rest';
        }
      }
    }

    // 6. Check dynamic cache
    final langCache = _dynamicCache[code];
    if (langCache != null && langCache.containsKey(text)) {
      return langCache[text]!;
    }

    // 7. Trigger background translation for newly encountered dynamic string
    _translateAsyncInBackground(text, code);

    return text;
  }

  /// Background auto-translator for dynamic backend text (product names, complaints)
  static final Set<String> _pendingTranslations = {};

  static void _translateAsyncInBackground(String text, String targetCode) async {
    final cacheKey = '$targetCode:$text';
    if (_pendingTranslations.contains(cacheKey)) return;
    _pendingTranslations.add(cacheKey);

    try {
      final url = Uri.parse(
        'https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=$targetCode&dt=t&q=${Uri.encodeComponent(text)}',
      );

      final response = await http.get(url).timeout(const Duration(seconds: 4));
      if (response.statusCode == 200) {
        final decoded = jsonDecode(response.body);
        if (decoded is List && decoded.isNotEmpty && decoded[0] is List) {
          final translated = decoded[0].map((item) => item[0]).join('');
          if (translated.isNotEmpty) {
            _dynamicCache.putIfAbsent(targetCode, () => {})[text] = translated;
            // Notify listeners so widget updates seamlessly
            languageNotifier.refresh();
          }
        }
      }
    } catch (_) {
      // Graceful fallback to original text
    } finally {
      _pendingTranslations.remove(cacheKey);
    }
  }

